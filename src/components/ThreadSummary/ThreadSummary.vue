<template>
  <section class="thread-summary" :aria-busy="pending ? 'true' : 'false'">
    <header class="summary-header">
      <span class="summary-title">
        <CreationIcon :size="20" />
        {{ afterPostId > 0 ? strings.unreadTitle : strings.title }}
      </span>
      <span class="summary-badge">{{ strings.aiGenerated }}</span>
      <NcButton
        variant="tertiary"
        class="summary-close"
        :aria-label="strings.close"
        :title="strings.close"
        @click="$emit('close')"
      >
        <template #icon>
          <CloseIcon :size="20" />
        </template>
      </NcButton>
    </header>

    <div v-if="pending" class="summary-pending">
      <NcLoadingIcon :size="20" />
      <span class="muted">{{ strings.generating }}</span>
    </div>

    <div v-else-if="error" class="summary-error">
      <span>{{ error }}</span>
      <NcButton @click="start">
        {{ strings.retry }}
      </NcButton>
    </div>

    <p v-else class="summary-text">{{ summary }}</p>

    <p v-if="!pending && !error" class="summary-disclaimer muted">{{ strings.disclaimer }}</p>
  </section>
</template>

<script lang="ts">
import { defineComponent } from 'vue'
import NcButton from '@nextcloud/vue/components/NcButton'
import NcLoadingIcon from '@nextcloud/vue/components/NcLoadingIcon'
import CreationIcon from '@icons/Creation.vue'
import CloseIcon from '@icons/Close.vue'
import { ocs } from '@/axios'
import { t } from '@nextcloud/l10n'

export interface ThreadSummaryTask {
  taskId: number | null
  status: 'scheduled' | 'running' | 'successful' | 'failed'
  summary: string | null
}

/** Delay before the first status check, growing up to the maximum while the task is pending */
const INITIAL_POLL_DELAY = 2000
const MAX_POLL_DELAY = 10000

export default defineComponent({
  name: 'ThreadSummary',
  components: {
    NcButton,
    NcLoadingIcon,
    CreationIcon,
    CloseIcon,
  },
  props: {
    threadId: {
      type: Number,
      required: true,
    },
    /** Summarize only replies newer than this post; 0 summarizes the whole thread */
    afterPostId: {
      type: Number,
      default: 0,
    },
  },
  emits: ['close'],
  data() {
    return {
      pending: false,
      summary: null as string | null,
      error: null as string | null,
      pollTimer: null as ReturnType<typeof setTimeout> | null,
      pollDelay: INITIAL_POLL_DELAY,
      strings: {
        title: t('forum', 'Thread summary'),
        unreadTitle: t('forum', 'Summary of unread replies'),
        aiGenerated: t('forum', 'AI-generated'),
        close: t('forum', 'Close summary'),
        generating: t('forum', 'Generating summary …'),
        retry: t('forum', 'Retry'),
        failed: t('forum', 'The summary could not be generated.'),
        disclaimer: t(
          'forum',
          'This summary was generated by AI and may contain mistakes. Only you can see it.',
        ),
      },
    }
  },
  created() {
    this.start()
  },
  beforeUnmount() {
    this.stopPolling()
  },
  methods: {
    async start(): Promise<void> {
      this.stopPolling()
      this.pending = true
      this.error = null
      this.summary = null
      this.pollDelay = INITIAL_POLL_DELAY
      try {
        const resp = await ocs.post<ThreadSummaryTask>(`/threads/${this.threadId}/summary`, {
          afterPostId: this.afterPostId,
        })
        this.handleTask(resp.data)
      } catch (e) {
        console.error('Failed to request thread summary', e)
        this.fail()
      }
    },

    async poll(taskId: number): Promise<void> {
      try {
        const resp = await ocs.get<ThreadSummaryTask>(`/threads/${this.threadId}/summary/${taskId}`)
        this.handleTask(resp.data)
      } catch (e) {
        console.error('Failed to fetch thread summary', e)
        this.fail()
      }
    },

    handleTask(task: ThreadSummaryTask): void {
      if (task.status === 'successful') {
        this.pending = false
        this.summary = task.summary ?? ''
        return
      }
      if (task.status === 'failed' || task.taskId === null) {
        this.fail()
        return
      }
      const taskId = task.taskId
      this.pollTimer = setTimeout(() => this.poll(taskId), this.pollDelay)
      this.pollDelay = Math.min(this.pollDelay * 1.5, MAX_POLL_DELAY)
    },

    fail(): void {
      this.pending = false
      this.error = this.strings.failed
    },

    stopPolling(): void {
      if (this.pollTimer !== null) {
        clearTimeout(this.pollTimer)
        this.pollTimer = null
      }
    },
  },
})
</script>

